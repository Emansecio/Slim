def dump(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def sha(data):
    return hashlib.sha256(data).hexdigest()


def put(root, files):
    for name, content in files.items():
        p = root / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(content.encode())


def env():
    result = dict(os.environ)
    # Explicit isolated run config, without changing global configuration or credentials.
    for key in list(result):
        if key.startswith("SLIM_") and not any(s in key for s in ("KEY", "TOKEN", "AUTH")):
            result.pop(key)
    result.update(SLIM_CONFIG_FILE=str(ROOT / "config.toml"),
                  RUSTC=str(TOOLCHAIN / "rustc.exe"),
                  RUSTDOC=str(TOOLCHAIN / "rustdoc.exe"),
                  CARGO_BUILD_JOBS="1", RUSTC_WRAPPER="")
    return result


def command(args, cwd, timeout=120):
    return subprocess.run(args, cwd=cwd, env=env(), capture_output=True,
                          creationflags=FLAGS, timeout=timeout)


